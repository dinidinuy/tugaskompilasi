display(HTML(CSS + """
<div class='bm-box'>
  <div class='bm-title'>🤖 BAHASA KITA → BAHASA MESIN</div>
  <div class='bm-sub'>Ketik kalimat, lalu lihat kode ASCII &amp; biner-nya</div>
</div>"""))

input_teks = widgets.Textarea(
    value="Halo Dunia",
    placeholder="Ketik teks atau biner di sini...",
    layout=widgets.Layout(width="95%", height="80px"),
)
btn_mesin = widgets.Button(description="Teks → Mesin", button_style="info",
                           icon="cogs", layout=widgets.Layout(width="160px"))
btn_teks = widgets.Button(description="Biner → Teks", button_style="warning",
                          icon="font", layout=widgets.Layout(width="160px"))
btn_hapus = widgets.Button(description="Bersihkan", button_style="danger",
                           icon="trash", layout=widgets.Layout(width="160px"))
output = widgets.Output()


def tampil_teks_ke_mesin(_=None):
    teks = input_teks.value
    with output:
        clear_output()
        if not teks:
            display(HTML("<div class='bm-err'>Masukkan teks dulu ya.</div>"))
            return
        baris_html = "".join(
            f"<tr><td>{html.escape(n)}</td><td>{k}</td><td>{h}</td><td>{b}</td></tr>"
            for n, k, h, b in teks_ke_baris(teks)
        )
        asc = " ".join(str(ord(c)) for c in teks)
        biner = " ".join(b[3] for b in teks_ke_baris(teks))
        display(HTML(f"""{CSS}
        <table class='bm-tbl'>
          <tr><th>Karakter</th><th>ASCII (Desimal)</th><th>Hex</th><th>Biner</th></tr>
          {baris_html}
        </table>
        <div class='bm-res'><b>ASCII :</b> {asc}<br><br><b>Biner :</b> {biner}</div>"""))


def tampil_biner_ke_teks(_=None):
    with output:
        clear_output()
        try:
            hasil = biner_ke_teks(input_teks.value)
            display(HTML(f"{CSS}<div class='bm-res'><b>Teks :</b> {html.escape(hasil)}</div>"))
        except ValueError as e:
            display(HTML(f"{CSS}<div class='bm-err'>Error: {html.escape(str(e))}</div>"))


def bersihkan(_=None):
    input_teks.value = ""
    with output:
        clear_output()


btn_mesin.on_click(tampil_teks_ke_mesin)
btn_teks.on_click(tampil_biner_ke_teks)
btn_hapus.on_click(bersihkan)

display(input_teks, widgets.HBox([btn_mesin, btn_teks, btn_hapus]), output)
tampil_teks_ke_mesin()